# ---------------------------------------------------------------- 共通の体裁
def doc(title, sub, lead, articles):
    out = '''
  <section class="ph ph--big">
    <div class="wrap grid">
      <h1>%s</h1>
      <p class="ph__sub">%s</p>
    </div>
  </section>

  <section class="field">
    <div class="wrap grid">
      <aside class="meta rise">
        <div><dt>この文書</dt><dd>%s</dd></div>
        <div><dt>対象</dt><dd>当社が提供する<br>すべてのサービス</dd></div>
        <div><dt>連絡先</dt><dd><a href="mailto:info@ligula.jp">info@ligula.jp</a></dd></div>
        <div><dt>関連</dt><dd><a href="/terms-of-service/">利用規約</a><br><a href="/privacy-policy/">プライバシーポリシー</a><br><a href="/law-1/">特定商取引法に基づく表記</a></dd></div>
      </aside>
      <div class="doc rise">
        <p class="doc__lead rise">%s</p>
''' % (title, sub, title.replace('<br>', ''), lead)
    for h, blocks in articles:
        out += '        <h2 class="rise">%s</h2>\n' % h
        for b in blocks:
            if isinstance(b, list):
                out += '        <ol>\n' + "".join('          <li>%s</li>\n' % li for li in b) + '        </ol>\n'
            elif isinstance(b, tuple):
                out += '        <ul>\n' + "".join('          <li>%s</li>\n' % li for li in b) + '        </ul>\n'
            else:
                out += '        <p class="rise">%s</p>\n' % b
    out += '''        <p class="doc__end">以上</p>
      </div>
    </div>
  </section>
'''
    return out + LAWNAV

